"""Generate offline legal pages and native license text from reviewed local inputs."""
import argparse
import html
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
NOTICE_FILES = ("LICENSE", "NOTICE.txt",
                "notices/Apache-2.0.txt", "notices/Kotlin-NOTICE.txt",
                "notices/JetBrains-Annotations.txt",
                "notices/Python-3.11.0.txt", "notices/dump978-GPL-2.0.txt")


def page(title, body):
    return ('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            '<title>' + title + '</title><link rel="stylesheet" href="app.css">'
            '<script src="legal.js" defer></script></head><body class="legal dark"><main><a href="/">Back to Sentry Bridge</a>'
            '<h1>' + title + '</h1>' + body + '</main></body></html>\n')


def generated(root=ROOT):
    privacy = (root / "docs/Privacy.md").read_text(encoding="utf-8")
    paragraphs = []
    for block in privacy.strip().split("\n\n"):
        if block.startswith("# "):
            continue
        if block.startswith("## "):
            paragraphs.append("<h2>" + html.escape(block[3:]) + "</h2>")
        else:
            paragraphs.append("<p>" + html.escape(block.replace("\n", " ")) + "</p>")
    body = '<p>Components vary by platform; Android has Kotlin, packaged Windows tools have Python. '
    body += 'The license texts below preserve their respective terms.</p>'
    for name in NOTICE_FILES:
        body += "<h2>" + html.escape(name) + "</h2><pre>" + html.escape(
            (root / name).read_text(encoding="utf-8")) + "</pre>"
    # Keep the native console self-contained without requiring a sibling license file.
    text = "\n\n".join((root / n).read_text(encoding="utf-8")
                           for n in ("NOTICE.txt", "LICENSE", "notices/dump978-GPL-2.0.txt"))
    # One small string per source line avoids MSVC's single-literal size limit.
    import json
    header = ('/* Generated by tools/legal_assets.py; do not edit. */\n'
              '#ifndef SB_LICENSE_TEXT_H\n#define SB_LICENSE_TEXT_H\n'
              'static const char *const SB_LICENSE_LINES[] = {\n' +
              ",\n".join("    " + json.dumps(line + "\n", ensure_ascii=True)
                           for line in text.splitlines()) +
              ',\n    0\n};\n#endif\n')
    return {"web/privacy.html": page("Privacy", "".join(paragraphs)),
            "web/legal.html": page("Licenses", body), "core/license_text.h": header}


def current(path, content):
    """A core.autocrlf checkout holds the same text with CRLF line ends."""
    return path.is_file() and path.read_bytes().replace(b"\r\n", b"\n") == content.encode("utf-8")


def check_python_runtime(root=ROOT):
    license_file = Path(sys.base_prefix) / "LICENSE.txt"
    expected = root / "notices/Python-3.11.0.txt"
    if sys.version_info[:3] != (3, 11, 0) or not license_file.is_file() or (
            [line.rstrip() for line in license_file.read_text(encoding="utf-8").splitlines()] !=
            [line.rstrip() for line in expected.read_text(encoding="utf-8").splitlines()]):
        raise ValueError("Windows packaging runtime changed: audit its licenses and update legal assets first.")


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--python-runtime", action="store_true")
    args = parser.parse_args()
    if args.python_runtime:
        check_python_runtime()
    for name, content in generated().items():
        path = ROOT / name
        if args.check:
            if not current(path, content):
                raise ValueError("Regenerate legal assets: " + name)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    print("Legal assets verified" if args.check else "Legal assets generated")


if __name__ == "__main__":
    main()
